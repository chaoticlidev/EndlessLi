//! `el-core`: domain types, errors, and shared traits.
//!
//! Why this crate exists: every other `el-*` crate depends on the same
//! error type and ID conventions. Centralizing them here keeps IPC error
//! shapes (`{ kind, message }`) consistent from Phase 1 onward.

